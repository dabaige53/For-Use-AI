"""Build the static assets used by the web animation.

* ``js/data.js``: narration duration and subtitles, read from the accepted
  narration (生成/配音/旁白.wav and 字幕.srt).  Chapters live in js/scene.js.
* ``fonts/fonts.js``: subset WOFF fonts (base64) for every character that the
  scene code and subtitles use.  The page then works from file:// without
  network access.  Source fonts are passed on the command line because they
  are not stored in the repository (Noto Serif SC and JetBrains Mono, OFL).

Usage (fontTools required):
    uv run --with fonttools python build_assets.py \
        --serif NotoSerifSC[wght].ttf --mono JetBrainsMono[wght].ttf
    uv run --with fonttools python build_assets.py --data-only
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import re
import wave
from pathlib import Path

HERE = Path(__file__).resolve().parent
LESSON = HERE.parents[1]  # AI的输入与输出/
NARRATION = LESSON / "生成" / "配音" / "旁白.wav"
SUBTITLES = LESSON / "生成" / "配音" / "字幕.srt"
DATA_JS = HERE / "js" / "data.js"
FONTS_JS = HERE / "fonts" / "fonts.js"
SCENE_SOURCES = sorted((HERE / "js").glob("*.js"))

# Glyphs that are drawn as vector shapes instead of text.
VECTOR_ONLY = set("✓✗")


def parse_srt(text: str) -> list[dict]:
    cues = []
    for block in re.split(r"\n\s*\n", text.strip()):
        lines = block.strip().splitlines()
        if len(lines) < 3:
            continue
        match = re.match(r"(\d+):(\d+):(\d+)[,.](\d+)\s*-->\s*(\d+):(\d+):(\d+)[,.](\d+)", lines[1])
        if not match:
            continue
        h1, m1, s1, ms1, h2, m2, s2, ms2 = map(int, match.groups())
        start = h1 * 3600 + m1 * 60 + s1 + ms1 / 1000
        end = h2 * 3600 + m2 * 60 + s2 + ms2 / 1000
        cues.append({"start": round(start, 3), "end": round(end, 3), "text": " ".join(lines[2:]).strip()})
    return cues


def build_data() -> dict:
    with wave.open(str(NARRATION), "rb") as audio:
        duration = audio.getnframes() / audio.getframerate()
    data = {
        "duration": round(duration, 3),
        "fps": 30,
        "size": [1920, 1080],
        "subtitles": parse_srt(SUBTITLES.read_text(encoding="utf-8")),
        "audio": "../../生成/配音/旁白.wav",
    }
    DATA_JS.write_text(
        "/* Generated by build_assets.py from 旁白.wav and 字幕.srt. Do not edit. */\n"
        "window.AIIO_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    return data


def collect_characters(data: dict) -> set[str]:
    chars = {chr(c) for c in range(32, 127)}
    chars |= set("，。、：；？！“”‘’（）《》【】—…·•→←↑↓×")
    for path in SCENE_SOURCES:
        if path.name in {"data.js"}:
            continue
        chars |= set(path.read_text(encoding="utf-8"))
    for cue in data["subtitles"]:
        chars |= set(cue["text"])
    return {c for c in chars if c.isprintable() and c not in VECTOR_ONLY}


def rename_font(font, family: str) -> None:
    """Modified OFL fonts get their own name; copyright and license stay."""
    table = font["name"]
    for record in list(table.names):
        if record.nameID in (1, 3, 4, 6, 16, 17, 21, 22):
            table.removeNames(nameID=record.nameID)
    postscript = re.sub(r"[^A-Za-z0-9-]", "", family.replace(" ", "-"))
    for name_id, value in ((1, family), (2, "Regular"), (3, family + " (subset)"), (4, family), (6, postscript)):
        table.setName(value, name_id, 3, 1, 0x409)
        table.setName(value, name_id, 1, 0, 0)


def subset_font(source: Path, weight: int | None, characters: set[str], family: str) -> tuple[bytes, list[str]]:
    from fontTools import subset
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer

    font = TTFont(source)
    if "fvar" in font and weight is not None:
        font = instancer.instantiateVariableFont(font, {"wght": weight}, inplace=False)
    cmap = font.getBestCmap()
    missing = sorted(c for c in characters if ord(c) not in cmap and not c.isspace())
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.hinting = False
    options.notdef_outline = True
    options.drop_tables += ["GSUB", "GPOS", "GDEF", "BASE", "STAT", "vhea", "vmtx", "VORG", "DSIG", "MVAR", "HVAR"]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[ord(c) for c in characters if ord(c) in cmap])
    subsetter.subset(font)
    rename_font(font, family)
    font.flavor = "woff"
    buffer = io.BytesIO()
    font.save(buffer)
    return buffer.getvalue(), missing


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--serif", type=Path, help="Noto Serif SC variable font (TTF)")
    parser.add_argument("--mono", type=Path, help="JetBrains Mono variable font (TTF)")
    parser.add_argument("--weights", default="600,800", help="serif weights, comma separated")
    parser.add_argument("--mono-weight", type=int, default=500)
    parser.add_argument("--data-only", action="store_true", help="only rebuild js/data.js")
    args = parser.parse_args()

    data = build_data()
    print(f"data.js: {len(data['subtitles'])} subtitles, {data['duration']} s")
    if args.data_only:
        return
    if not args.serif or not args.mono:
        parser.error("--serif and --mono are required unless --data-only is given")

    characters = collect_characters(data)
    cjk = {c for c in characters if ord(c) > 127}
    fonts: dict[str, str] = {}
    report = {}
    for weight in (int(w) for w in args.weights.split(",")):
        blob, missing = subset_font(args.serif, weight, characters, f"AIIO Serif SC {weight}")
        fonts[f"serif{weight}"] = base64.b64encode(blob).decode("ascii")
        report[f"serif{weight}"] = (len(blob), missing)
    ascii_chars = {c for c in characters if ord(c) < 0x2500} - cjk | set("→←↑↓×…·•")
    blob, missing = subset_font(args.mono, args.mono_weight, ascii_chars, f"AIIO Mono {args.mono_weight}")
    fonts["mono"] = base64.b64encode(blob).decode("ascii")
    report["mono"] = (len(blob), missing)

    FONTS_JS.write_text(
        "/* Generated by build_assets.py: subset of Noto Serif SC and JetBrains Mono (SIL OFL 1.1,\n"
        "   see OFL-*.txt). Base64 WOFF so that index.html also works from file://. */\n"
        "window.AIIO_FONTS = " + json.dumps(fonts) + ";\n",
        encoding="ascii",
    )
    for key, (size, missing) in report.items():
        shown = "".join(missing[:40])
        print(f"{key}: {size / 1024:.0f} KiB, missing {len(missing)}: {shown}")
    print(f"fonts.js: {FONTS_JS.stat().st_size / 1024:.0f} KiB, {len(cjk)} non-ASCII characters")


if __name__ == "__main__":
    main()
